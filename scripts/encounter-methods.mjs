// Writes src/constants/methods.ts from scripts/encounter-methods.json, the result of
// scripts/encounter-methods.browser.js (run on Bulbapedia; see that file). Run it after saving
// a new result:
//
//   node scripts/encounter-methods.mjs
//
// Only the tags go into the app; this never changes the encounter tables. The result's
// `notOnPage` and `noPage` lists are entries Bulbapedia's location pages don't cover, which stay
// untagged (shown as plain wild encounters). See CLAUDE.md.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(import.meta.url), '../..');
const SOURCE = join(ROOT, 'scripts/encounter-methods.json');
const OUT = join(ROOT, 'src/constants/methods.ts');

// methods.ts's source for a result's tags, keys in the result's order
export function render(tags) {
  return `// Generated by scripts/encounter-methods.mjs from Bulbapedia; don't edit by hand.
// How the Pokémon in an encounter table are met at their location when it isn't a plain wild
// encounter. Any other Pokémon in the table is met in the wild there.
import type { TMethods } from 'constants/versions';

const METHODS: TMethods = ${JSON.stringify(tags)};

export default METHODS;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { tags } = JSON.parse(readFileSync(SOURCE, 'utf8'));
  writeFileSync(OUT, render(tags));
  execFileSync('npx', ['prettier', '--write', OUT], { cwd: ROOT, stdio: 'inherit' });
}
