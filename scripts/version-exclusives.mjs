// Writes src/constants/exclusives.ts from scripts/version-exclusives.json, the result of
// scripts/version-exclusives.browser.js (run on Bulbapedia; see that file). Run it after saving
// a new result:
//
//   node scripts/version-exclusives.mjs
//
// Only the tags go into the app; this never changes the encounter tables. Of the result's lists,
// `missing` entries found in some versions only belong in their tables (add them in filters.ts
// and rerun the browser script); `unplaced` entries stay untagged, and `unknown` names are
// questions for the user. See CLAUDE.md.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(import.meta.url), '../..');
const SOURCE = join(ROOT, 'scripts/version-exclusives.json');
const OUT = join(ROOT, 'src/constants/exclusives.ts');

// exclusives.ts's source for a result's tags, keys in the result's order
export function render(tags) {
  return `// Generated by scripts/version-exclusives.mjs from Bulbapedia; don't edit by hand.
// The Pokémon in an encounter table that appear only in the listed versions. Any other Pokémon in
// the table appears in every version of its game.
import type { TExclusives } from 'constants/versions';

const EXCLUSIVES: TExclusives = ${JSON.stringify(tags)};

export default EXCLUSIVES;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { tags } = JSON.parse(readFileSync(SOURCE, 'utf8'));
  writeFileSync(OUT, render(tags));
  execFileSync('npx', ['prettier', '--write', OUT], { cwd: ROOT, stdio: 'inherit' });
}
